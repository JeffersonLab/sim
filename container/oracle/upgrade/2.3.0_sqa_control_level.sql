-- Replace the summed Downtime Risk with the derived SQA Control Level and Attention band
-- (JeffersonLab/sim#39). Run once, as SIM_OWNER or a user that may alter its table. The
-- definitions must match container/oracle/initdb.d/02_ddl.sql.

ALTER TABLE SIM_OWNER.SOFTWARE DROP COLUMN DOWN_PROBABILITY;
ALTER TABLE SIM_OWNER.SOFTWARE DROP COLUMN DOWNTIME_RISK;

ALTER TABLE SIM_OWNER.SOFTWARE ADD (
   CONTROL_LEVEL_OVERRIDE  SMALLINT NULL,
   CONTROL_LEVEL_NOTE      VARCHAR2(512 CHAR) NULL,
   ASSESSED_BY             VARCHAR2(64 CHAR) NULL,
   ASSESSED_DATE           DATE NULL,
   FRAGILITY               SMALLINT GENERATED ALWAYS AS (GREATEST(PAST_DOWNTIME, DEBUGGABILITY_N_TESTING, CODE_COMPLEXITY, DOCUMENTATION_GAPS, ESOTERICISM)) VIRTUAL,
   CONTROL_LEVEL           SMALLINT GENERATED ALWAYS AS (CASE WHEN OPS_IMPACT = 5 THEN 3 ELSE LEAST(3, (CASE WHEN OPS_IMPACT <= 2 THEN 1 WHEN OPS_IMPACT = 3 THEN 2 ELSE 3 END) + (CASE WHEN CODE_COMPLEXITY <= 2 THEN 1 WHEN CODE_COMPLEXITY = 3 THEN 2 ELSE 3 END) - 2) END) VIRTUAL,
   ATTENTION               SMALLINT GENERATED ALWAYS AS (CASE WHEN OPS_IMPACT + GREATEST(PAST_DOWNTIME, DEBUGGABILITY_N_TESTING, CODE_COMPLEXITY, DOCUMENTATION_GAPS, ESOTERICISM) <= 4 THEN 1 WHEN OPS_IMPACT + GREATEST(PAST_DOWNTIME, DEBUGGABILITY_N_TESTING, CODE_COMPLEXITY, DOCUMENTATION_GAPS, ESOTERICISM) <= 6 THEN 2 WHEN OPS_IMPACT + GREATEST(PAST_DOWNTIME, DEBUGGABILITY_N_TESTING, CODE_COMPLEXITY, DOCUMENTATION_GAPS, ESOTERICISM) <= 8 THEN 3 ELSE 4 END) VIRTUAL
);

ALTER TABLE SIM_OWNER.SOFTWARE ADD CONSTRAINT SOFTWARE_CK9 CHECK (CONTROL_LEVEL_OVERRIDE IN (0, 1, 2, 3));
ALTER TABLE SIM_OWNER.SOFTWARE ADD CONSTRAINT SOFTWARE_CK10 CHECK (CONTROL_LEVEL_OVERRIDE IS NULL OR CONTROL_LEVEL_NOTE IS NOT NULL);

-- Software somebody already graded (any input changed from its default of 3) counts as assessed,
-- by an unknown user; software still at the defaults shows as Not assessed.
UPDATE SIM_OWNER.SOFTWARE
   SET ASSESSED_DATE = SYSDATE
 WHERE ASSESSED_DATE IS NULL
   AND (OPS_IMPACT <> 3 OR PAST_DOWNTIME <> 3 OR DEBUGGABILITY_N_TESTING <> 3
        OR CODE_COMPLEXITY <> 3 OR DOCUMENTATION_GAPS <> 3 OR ESOTERICISM <> 3);

COMMIT;
