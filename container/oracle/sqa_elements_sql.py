"""Write the SQL that loads the ACS SQAP's required SQA elements into SIM_OWNER.SQA_ELEMENT.

The elements come from the SQAP's elements.json, which its build makes from the plan's tables and
publishes beside each revision (https://code.jlab.org/acc/iac/docs/sqap, README, "Required SQA
elements as data"). Never type the elements into SQL by hand: run this on the revision's file::

    python3 container/oracle/sqa_elements_sql.py elements.json > container/oracle/initdb.d/03_sqa_elements.sql

Only the elements whose scope is "product" are loaded: those a product has or lacks as a whole,
which SIM records for each product. A file whose "draft" is true is not a released revision of
the plan: it is refused unless --draft is given, and then the version says that it is a draft.

For a database that already has elements, write the upgrade script by hand from this output:
an element's id never changes, so update the rows whose id is already there and insert the rest.
"""

from __future__ import annotations

import argparse
import json
import sys

SITE = "https://pages.jlab.org/acc/iac/docs/sqap"
LEVELS = ("minimal", "partial", "significant", "full")
REQUIREMENTS = {"required": "REQUIRED", "recommended": "RECOMMENDED", None: None}


def literal(value: str | None) -> str:
    return "null" if value is None else "'" + value.replace("'", "''") + "'"


def sql(data: dict, allow_draft: bool) -> str:
    if data["levels"] != list(LEVELS):
        raise SystemExit(f"The file's levels are {data['levels']}, not {list(LEVELS)}")
    if data["draft"] and not allow_draft:
        raise SystemExit("The file is a draft, not a released revision of the plan (--draft loads it anyway)")
    if data["draft"]:
        version = f"draft {data['revision']} after {data['version']}"
        folder = "latest"  # A draft has no folder of its own on the site
    else:
        version = data["version"]
        folder = f"v{data['version']}"
    lines = [
        "alter session set container = XEPDB1;",
        "",
        f"-- The ACS SQAP's required SQA elements of a product, revision: {version}.",
        "-- Generated by container/oracle/sqa_elements_sql.py from the SQAP's elements.json: do not edit.",
        "SET DEFINE OFF;",
        "",
    ]
    weight = 0
    for element in data["elements"]:
        if element["scope"] != "product":
            continue
        weight += 1
        values = [
            literal(element["id"]),
            literal(element["name"]),
            literal(element["phase"]),
            literal(element["section"]["number"]),
            literal(f"{SITE}/{folder}/{element['section']['url']}"),
            str(weight),
            *(literal(REQUIREMENTS[element["levels"][level]]) for level in LEVELS),
            literal(version),
        ]
        lines.append(
            "insert into SIM_OWNER.SQA_ELEMENT (ELEMENT_ID, NAME, PHASE, SECTION_NUMBER, SECTION_URL, WEIGHT,"
            " LEVEL_0, LEVEL_1, LEVEL_2, LEVEL_3, SQAP_VERSION) values (" + ", ".join(values) + ");"
        )
    lines += ["", "commit;", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("file", help="the SQAP's elements.json")
    parser.add_argument("--draft", action="store_true", help="load a file that is not a released revision")
    args = parser.parse_args()
    with open(args.file, encoding="utf-8") as source:
        sys.stdout.write(sql(json.load(source), args.draft))
    return 0


if __name__ == "__main__":
    sys.exit(main())
